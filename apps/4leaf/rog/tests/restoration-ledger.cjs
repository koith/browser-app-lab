'use strict';
const assert=require('node:assert/strict');
const {spawnSync}=require('node:child_process');
const path=require('node:path');
const {validate,read,REQUIRED}=require('../tools/restoration-ledger.cjs');
const clone=value=>JSON.parse(JSON.stringify(value));
const base=read();
assert.equal(validate(base),base,'actual ledger has a valid schema');
assert.equal(base.tasks.length,new Set(base.tasks.map(t=>t.id)).size);
for(const id of REQUIRED)assert.ok(base.tasks.some(t=>t.id===id),id+' protected');
const missing=clone(base);missing.tasks=missing.tasks.filter(t=>t.id!=='P0-BOARD');
assert.throws(()=>validate(missing),/removed/,'cannot lose P0 work');
const duplicate=clone(base);duplicate.tasks.push(clone(duplicate.tasks[0]));
assert.throws(()=>validate(duplicate),/duplicate task/);
const falseDone=clone(base);
falseDone.tasks.find(t=>t.id==='M06').status='done';
assert.throws(()=>validate(falseDone),/DO NOT mark done/,'a PR or a screenshot alone cannot assert original equivalence');
const unresearchedBlock=clone(base);
unresearchedBlock.tasks.find(t=>t.id==='M07').status='blocked';
assert.throws(()=>validate(unresearchedBlock),/blocked requires/,'cannot call a failed implementation path impossible');
const truncated=clone(base);truncated.intake=[];
assert.throws(()=>validate(truncated,base),/user request history truncated|event refers to missing request/);
const rewritten=clone(base);rewritten.intake[0].text='rewrite the user history';
assert.throws(()=>validate(rewritten,base),/immutable user request/);
const wiped=clone(base);wiped.events=[];
assert.throws(()=>validate(wiped,base),/work history truncated/);
const unlogged=clone(base);
unlogged.tasks.find(t=>t.id==='M03').status='todo';
assert.throws(()=>validate(unlogged,base),/without audit event/);
const newTask=clone(base);
newTask.tasks.push({...clone(base.tasks[0]),id:'P1-NEW-001',status:'todo'});
assert.throws(()=>validate(newTask,base),/lacks registration event/);
const cli=spawnSync(process.execPath,[path.resolve(__dirname,'../tools/restoration-ledger.cjs'),'report','--json'],
 {encoding:'utf8'});
assert.equal(cli.status,0,cli.stderr);
const report=JSON.parse(cli.stdout);
assert.equal(report.tasks.length,base.tasks.length);
assert.equal(Object.values(report.counts).reduce((a,b)=>a+b,0),base.tasks.length);
console.log('RESTORATION LEDGER INTAKE / STATUS / HISTORY REGRESSION PASS',
 base.tasks.length,'tracked tasks,',base.intake.length,'requests');
