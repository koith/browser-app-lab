const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const base='https://koith.github.io/browser-app-lab/apps/4leaf/';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 const errors=[],invalid=[];
 page.on('pageerror',e=>errors.push(e.stack||e.message));
 page.on('response',r=>{if(r.status()>=400)invalid.push(r.status()+' '+r.url())});
 const first=await page.goto(base,{waitUntil:'domcontentloaded',timeout:40000});
 if(!first||!first.ok())throw Error('Public URL cannot load: '+(first?.status()??'NO_RESPONSE'));
 await page.waitForFunction(()=>!!window.__ROG_TEST__&&!!window.ORIGINAL_LEAF_TILES&&!!window.ORIGINAL_LEAF_CHESSMEN,null,{timeout:16000});
 await page.locator('[data-route="lobby"]').first().click();
 await page.locator('#lobby-create').click();
 await page.locator('#bot-count').selectOption('1');
 await page.locator('#start-game').click();
 await page.waitForSelector('#game:not(.hidden)',{timeout:8000});
 assert.equal(await page.locator('#board-nodes .tile').count(),104);
 const q=await page.evaluate(()=>({titles:Object.keys(window.ORIGINAL_LEAF_MAP_INFO).length,tiles:Object.keys(window.ORIGINAL_LEAF_TILES).length,chessmen:window.ORIGINAL_LEAF_CHESSMEN.length,originalMarker:window.ORIGINAL_LEAF_TILES["0172"][2]?.type,renderedMarker:window.__ROG_TEST__.getMatch().tiles[2]}));
 assert.equal(q.originalMarker,'boost4');
 assert.equal(q.renderedMarker,q.originalMarker);
 assert.ok(q.titles>=25&&q.tiles>=25&&q.chessmen>=90);
 await page.locator('#roll-btn').click();
 await page.waitForFunction(()=>window.__ROG_TEST__.getMatch().players[0].position>0,null,{timeout:15000});
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('#game img')).filter(el=>el.offsetParent!==null).every(el=>el.complete),null,{timeout:12000});
 const images=await page.locator('#game img').evaluateAll(list=>list.filter(el=>el.offsetParent!==null&&!el.naturalWidth).map(el=>el.src));
 assert.deepEqual(images,[],'visible source character textures must load');
 assert.deepEqual(invalid,[],'all requested public assets must exist');
 assert.deepEqual(errors,[],'no client script exceptions');
 await page.screenshot({path:'4leaf-live-mobile.png'});
 await browser.close();
 console.log('LIVE 4LEAF PUBLIC URL VERIFIED',base,q,'rendering and roll PASS');
})().catch(e=>{console.error('4LEAF LIVE FAIL:',e);process.exit(1)});